#!/usr/bin/env node
/** Builds signed update metadata from the actual Windows artifact. Publishes nothing. */
import { createHash } from 'node:crypto'
import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, resolve } from 'node:path'
import { ed25519 } from '@noble/curves/ed25519.js'
import { signManifest, verifyManifest } from '../packages/engine/dist/update/updater.js'

const [installerPath, notesPath, outputPath] = process.argv.slice(2)
if (!installerPath || !notesPath || !outputPath) throw new Error('Usage: prepare-update-release.mjs <installer.exe> <release-notes.md> <signed-manifest.json>')
const version = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version
const desktopVersion = JSON.parse(readFileSync(new URL('../apps/desktop/package.json', import.meta.url), 'utf8')).version
if (version !== desktopVersion) throw new Error('Root and desktop versions differ')
const name = basename(installerPath)
const match = /^Hydra-Setup-([\dA-Za-z.-]+)-(x64|arm64)\.exe$/.exec(name)
if (!match || match[1] !== version) throw new Error('Installer name must match this exact version and architecture')
const key = process.env.HYDRA_UPDATE_SIGNING_KEY?.trim()
const publicKey = process.env.HYDRA_UPDATE_KEY?.trim()
if (!key || !/^[0-9a-f]{64}$/.test(key) || !publicKey || !/^[0-9a-f]{64}$/.test(publicKey)) throw new Error('A publisher signing key and its public key are required; neither is generated by this tool')
if (Buffer.from(ed25519.getPublicKey(Buffer.from(key, 'hex'))).toString('hex') !== publicKey) throw new Error('Signing key does not match the public key embedded in this build')
const manifest = {
  schema: 1, version, releasedAt: new Date().toISOString(), notes: readFileSync(notesPath, 'utf8'),
  issuedAt: new Date().toISOString(), expiresAt: new Date(Date.now()+30*86400000).toISOString(),
  files: [{ platform: `win32-${match[2]}`, name, url: `https://github.com/MoallaMelek/Hydra-Agent-Orchestrator/releases/download/v${version}/${name}`, size: statSync(installerPath).size, sha256: createHash('sha256').update(readFileSync(installerPath)).digest('hex') }]
}
const signed = { manifest, signature: signManifest(manifest, key) }
verifyManifest(signed, publicKey)
writeFileSync(resolve(outputPath), JSON.stringify(signed, null, 2))
console.log(`Prepared authenticated metadata for ${version}; no release was published.`)
