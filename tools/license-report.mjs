#!/usr/bin/env node
// Lists every third-party package that ships in Hydra v2 (runtime dependencies of
// the shipped workspaces) with its licence, and fails on licences that would
// restrict commercial distribution. Writes docs/v2/THIRD_PARTY.md.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const SHIPPED = ['packages/protocol', 'packages/engine', 'packages/secure-channel', 'packages/ui', 'apps/hydrad']
const ALLOWED = /^(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|Python-2\.0|\(MIT OR Apache-2\.0\)|MIT OR Apache-2\.0)$/

const manifest = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
function resolveDir(name, from) {
  for (let dir = from; ; dir = join(dir, '..')) {
    const candidate = join(dir, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    if (dir === join(dir, '..') || dir.length <= ROOT.length - 1) return existsSync(join(ROOT, 'node_modules', name, 'package.json')) ? join(ROOT, 'node_modules', name) : null
  }
}

const seen = new Map()
function visit(name, from) {
  const dir = resolveDir(name, from)
  if (!dir) return
  const pkg = manifest(dir)
  const key = `${pkg.name}@${pkg.version}`
  if (seen.has(key)) return
  const license = typeof pkg.license === 'string' ? pkg.license : Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN'
  seen.set(key, { name: pkg.name, version: pkg.version, license, repo: typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '' })
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir)
}

for (const ws of SHIPPED) {
  for (const dep of Object.keys(manifest(join(ROOT, ws)).dependencies ?? {})) {
    if (!dep.startsWith('@hydra/')) visit(dep, join(ROOT, ws))
  }
}

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))
const problems = rows.filter((r) => !ALLOWED.test(r.license))
const md = [
  '# Third-party components shipped with Hydra v2',
  '',
  `Generated by \`npm run licenses\` on ${new Date().toISOString().slice(0, 10)}. Runtime dependencies of the shipped workspaces only (build tools and Electron itself are listed separately below).`,
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
  '## Platform components (not npm runtime dependencies)',
  '- **Electron** (MIT) and the Chromium/Node.js components it bundles, under their own licences (see `LICENSES.chromium.html` in the packaged app).',
  '- **Claude Code** and **Codex CLI** are **not** shipped with Hydra. Customers install them and accept their own terms with their own accounts.',
  ''
].join('\n')
writeFileSync(join(ROOT, 'docs', 'v2', 'THIRD_PARTY.md'), md)
console.log(`${rows.length} shipped third-party packages; licences: ${[...new Set(rows.map((r) => r.license))].join(', ')}`)
if (problems.length) {
  console.error(`Licences needing review:\n${problems.map((p) => `- ${p.name}@${p.version}: ${p.license}`).join('\n')}`)
  process.exit(1)
}
